// Build the Cloudflare version.
//
//   node scripts/build_web.mjs                -> dist/ (the Pages site) + the Worker's config
//   node scripts/build_web.mjs --worker-only  -> only worker/src/config.generated.js
//
// dist/
//   index.html, css/, js/      the office UI (autoscorecard/server/static), booting via web/boot.js
//   sw.js, web/                service worker, page boot, Pyodide worker
//   assets/                    art (git-tracked files only)
//   py/bundle.json             the Python package, config.yaml and plugins, as text
//   wheels/                    pure-Python wheels not in Pyodide (sha256-checked)
//
// Needs Node 20+ only (no Python), so Cloudflare's build image can run it.

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");
const CACHE = join(ROOT, ".cache", "wheels");
const r = (...p) => join(ROOT, ...p);

function workerConfig() {
  const cfg = YAML.parse(readFileSync(r("config", "config.yaml"), "utf8"));
  const providers = {};
  for (const [name, p] of Object.entries(cfg.providers)) {
    if (p.type !== "anthropic" && p.type !== "openai_compat") continue;
    providers[name] = { type: p.type, model: p.model, key_env: p.key_env, max_tokens: p.max_tokens ?? 4096,
      price: { input: 0, output: 0, ...(p.price || {}) } };
  }
  const out = { providers, budget: { total_usd: cfg.budget?.total_usd ?? 4.5 } };
  writeFileSync(r("worker", "src", "config.generated.js"),
    "// Generated by scripts/build_web.mjs from config/config.yaml. Do not edit.\n"
    + `export default ${JSON.stringify(out, null, 2)};\n`);
  console.log(`worker config: ${Object.keys(providers).length} providers, budget $${out.budget.total_usd}`);
}

function walk(dir, keep) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name !== "__pycache__" && !name.startsWith(".")) out.push(...walk(p, keep));
    } else if (keep(p)) out.push(p);
  }
  return out;
}

function gitFiles(path) {
  try {
    return execFileSync("git", ["ls-files", "-z", path], { cwd: ROOT }).toString().split("\0").filter(Boolean);
  } catch {
    return null;
  }
}

function version() {
  try { return execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: ROOT }).toString().trim(); }
  catch { return "dev"; }
}

function site() {
  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(DIST, { recursive: true });
  // the UI, unchanged except that it boots Python first
  cpSync(r("autoscorecard", "server", "static"), DIST, { recursive: true });
  const index = join(DIST, "index.html");
  const html = readFileSync(index, "utf8");
  const tag = '<script type="module" src="/js/main.js"></script>';
  if (!html.includes(tag)) throw new Error("index.html: main.js script tag not found");
  writeFileSync(index, html.replace(tag, '<script type="module" src="/web/boot.js"></script>'));
  mkdirSync(join(DIST, "web"));
  for (const f of ["boot.js", "py-worker.js"]) cpSync(r("web", f), join(DIST, "web", f));
  cpSync(r("web", "sw.js"), join(DIST, "sw.js"));
  cpSync(r("web", "_headers"), join(DIST, "_headers"));

  // art: tracked files only (the working folders are big and ignored)
  const assets = gitFiles("assets") ?? walk(r("assets"), (p) => !/[\\/]_(raw|originals)[\\/]/.test(p)).map((p) => relative(ROOT, p));
  for (const f of assets) {
    mkdirSync(dirname(join(DIST, f)), { recursive: true });
    cpSync(r(f), join(DIST, f));
  }

  // the Python code, as text the Pyodide worker writes under /app
  const files = {};
  const py = walk(r("autoscorecard"), (p) => p.endsWith(".py") && !p.includes(join("server", "static")));
  const plugins = existsSync(r("plugins")) ? walk(r("plugins"), (p) => p.endsWith(".py")) : [];
  for (const p of [...py, ...plugins, r("config", "config.yaml")]) files[relative(ROOT, p).split("\\").join("/")] = readFileSync(p, "utf8");
  mkdirSync(join(DIST, "py"));
  writeFileSync(join(DIST, "py", "bundle.json"), JSON.stringify({ version: version(), files }));
  console.log(`python bundle: ${Object.keys(files).length} files; assets: ${assets.length} files`);
}

async function wheels() {
  const { wheels } = JSON.parse(readFileSync(r("web", "wheels.json"), "utf8"));
  mkdirSync(CACHE, { recursive: true });
  mkdirSync(join(DIST, "wheels"));
  for (const w of wheels) {
    const cached = join(CACHE, w.file);
    if (!existsSync(cached)) {
      const res = await fetch(w.url);
      if (!res.ok) throw new Error(`${w.file}: download failed (${res.status})`);
      writeFileSync(cached, Buffer.from(await res.arrayBuffer()));
    }
    const sha = createHash("sha256").update(readFileSync(cached)).digest("hex");
    if (sha !== w.sha256) {
      rmSync(cached);
      throw new Error(`${w.file}: sha256 mismatch (got ${sha})`);
    }
    cpSync(cached, join(DIST, "wheels", w.file));
  }
  writeFileSync(join(DIST, "wheels", "index.json"), JSON.stringify(wheels.map((w) => w.file)));
  console.log(`wheels: ${wheels.length} verified`);
}

workerConfig();
if (!process.argv.includes("--worker-only")) {
  site();
  await wheels();
  console.log(`built ${relative(ROOT, DIST)}/ (${version()})`);
}
